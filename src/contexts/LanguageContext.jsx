const normalize = (value) => String(value).trim().replace(/\s+/g, ' ')
const entries = Object.entries(englishToItalian).map(([english, italian]) => [normalize(english), italian])
const toItalian = new Map(entries)
const toItalianFolded = new Map(entries.map(([english, italian]) => [english.toLocaleLowerCase('en'), italian]))
const toEnglish = new Map(entries.map(([english, italian]) => [normalize(italian), english]))
const toEnglishFolded = new Map(entries.map(([english, italian]) => [normalize(italian).toLocaleLowerCase('it'), english]))

const getInitialLanguage = () => {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
  return saved === 'en' || saved === 'it' ? saved : DEFAULT_LANGUAGE
}

const interpolate = (value, variables = {}) => String(value).replace(/\{(\w+)\}/g, (_, name) => variables[name] ?? `{${name}}`)

const LanguageContext = createContext(null)

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(getInitialLanguage)

  const setLanguage = useCallback((nextLanguage) => {
    const resolved = nextLanguage === 'en' ? 'en' : 'it'
    if (typeof window !== 'undefined') window.localStorage.setItem(LANGUAGE_STORAGE_KEY, resolved)
    setLanguageState(resolved)
  }, [])

  useEffect(() => {
    if (typeof window === 'undefined') return
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const translateText = useCallback((value, targetLanguage = language) => {
    if (value === null || value === undefined || value === '') return value
    const original = String(value)
    const leading = original.match(/^\s*/)?.[0] || ''
    const trailing = original.match(/\s*$/)?.[0] || ''
    const phrase = normalize(original)
    const english = toEnglish.get(phrase) || toEnglishFolded.get(phrase.toLocaleLowerCase('it')) || phrase
    const translated = targetLanguage === 'it'
      ? (toItalian.get(english) || toItalianFolded.get(english.toLocaleLowerCase('en')) || english)
      : english
    return `${leading}${translated}${trailing}`
  }, [language])

  // Legacy confirmation/alert calls bypass the DOM translation boundary.
  // Translating them here keeps the remaining native dialogs consistent with
  // the selected interface language without touching user-authored text.
  useEffect(() => {
    if (typeof window === 'undefined') return undefined
    const nativeConfirm = window.confirm.bind(window)
    const nativeAlert = window.alert.bind(window)
    window.confirm = (message) => nativeConfirm(translateText(message))
    window.alert = (message) => nativeAlert(translateText(message))
    return () => {
      window.confirm = nativeConfirm
      window.alert = nativeAlert
    }
  }, [translateText])

  const t = useCallback((value, variables = {}) => interpolate(translateText(value), variables), [translateText])
  const locale = language === 'it' ? 'it-IT' : 'en-US'
  const value = useMemo(() => ({
    language,
    locale,
    setLanguage,
    toggleLanguage: () => setLanguage(language === 'it' ? 'en' : 'it'),
    translateText,
    t,
  }), [language, locale, setLanguage, translateText, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export const useLanguage = () => {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider')
  return context
}

export default LanguageContext
